const translations: Record<Exclude<Language, 'zh-TW'>, Record<string, string>> = {
  en: Object.fromEntries(messages.map(([key, en]) => [key, en])),
  vi: Object.fromEntries(messages.map(([key, , vi]) => [key, vi])),
  ja: Object.fromEntries(messages.map(([key, , , ja]) => [key, ja])),
};

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const LANGUAGE_STORAGE_KEY = 'ydv-language';

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const savedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return LANGUAGE_OPTIONS.some((option) => option.code === savedLanguage) ? savedLanguage as Language : 'zh-TW';
  });

  useEffect(() => {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  return <LanguageContext.Provider value={{ language, setLanguage }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage must be used within LanguageProvider');
  return value;
}

export function useTranslation() {
  const { language } = useLanguage();
  return useCallback((key: string, values: Record<string, string | number> = {}) => {
    const template = language === 'zh-TW' ? key : translations[language][key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  }, [language]);
}
